    <p>
    <b>Apa itu anemia?</b><br>
    Anemia adalah suatu kondisi di mana jumlah sel darah merah atau konsentrasi hemoglobin dalam darah berada di bawah normal, sehingga tubuh kekurangan oksigen.
    </p>
    <p>
    <b>Gejala umum anemia:</b><br>
    Lemas/mudah lelah, pucat, pusing, sesak napas, jantung berdebar, tangan/kaki dingin, dan lainnya.
    </p>
    <p>
    <b>Penyebab anemia:</b><br>
    Kekurangan zat besi, vitamin B12, asam folat, kelainan genetik seperti thalassemia, penyakit kronis, infeksi, dll.
    </p>
    <p>
    <b>Penanganan:</b><br>
    Perbaikan pola makan, konsumsi suplemen, pengobatan sesuai penyebab anemia, konsultasi ke dokter atau puskesmas jika gejala berat.
    </p>
